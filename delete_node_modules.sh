#!/usr/bin/env bash
# Recursively find and delete all node_modules directories under a given directory.
set -euo pipefail

usage() {
    echo "Usage: $0 [--dry-run] [-y|--yes] <directory>"
    echo
    echo "  --dry-run     List node_modules directories that would be deleted without deleting them"
    echo "  -y, --yes     Delete without prompting for confirmation"
    exit 1
}

dry_run=false
assume_yes=false
target_dir=""

while [[ $# -gt 0 ]]; do
    case "$1" in
        --dry-run)
            dry_run=true
            shift
            ;;
        -y|--yes)
            assume_yes=true
            shift
            ;;
        -h|--help)
            usage
            ;;
        -*)
            echo "Unknown option: $1" >&2
            usage
            ;;
        *)
            if [[ -n "$target_dir" ]]; then
                echo "Error: unexpected argument '$1'" >&2
                usage
            fi
            target_dir="$1"
            shift
            ;;
    esac
done

if [[ -z "$target_dir" ]]; then
    echo "Error: directory argument is required" >&2
    usage
fi

if [[ ! -d "$target_dir" ]]; then
    echo "Error: '$target_dir' is not a valid directory" >&2
    exit 1
fi

root=$(cd "$target_dir" && pwd)

echo "Scanning '$root' for node_modules directories..."

mapfile -d '' matches < <(find "$root" -type d -name node_modules -prune -print0)

if [[ ${#matches[@]} -eq 0 ]]; then
    echo "No node_modules directories found."
    exit 0
fi

count=${#matches[@]}
if [[ $count -eq 1 ]]; then
    echo -e "\nFound 1 node_modules directory:"
else
    echo -e "\nFound $count node_modules directories:"
fi

total_size=0
for path in "${matches[@]}"; do
    size=$(du -sh "$path" 2>/dev/null | cut -f1)
    size_bytes=$(du -sb "$path" 2>/dev/null | cut -f1)
    total_size=$((total_size + size_bytes))
    echo "  $path ($size)"
done

total_human=$(numfmt --to=iec-i --suffix=B "$total_size" 2>/dev/null || echo "${total_size} B")
echo -e "\nTotal size: $total_human"

if [[ "$dry_run" == true ]]; then
    echo -e "\nDry run: no directories were deleted."
    exit 0
fi

if [[ "$assume_yes" != true ]]; then
    read -r -p $'\nDelete all listed node_modules directories? [y/N] ' answer
    if [[ ! "$answer" =~ ^[Yy]$ ]]; then
        echo "Aborted."
        exit 0
    fi
fi

deleted=0
for path in "${matches[@]}"; do
    if rm -rf "$path"; then
        deleted=$((deleted + 1))
        echo "Deleted: $path"
    else
        echo "Failed to delete: $path" >&2
    fi
done

echo -e "\nDeleted $deleted/$count node_modules directories."
