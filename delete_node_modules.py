#!/usr/bin/env python3
"""Recursively delete all node_modules directories under a given directory."""

import argparse
import os
import shutil
import sys


def find_node_modules(root):
    matches = []
    for dirpath, dirnames, _filenames in os.walk(root):
        if "node_modules" in dirnames:
            matches.append(os.path.join(dirpath, "node_modules"))
            # Don't descend into node_modules itself
            dirnames.remove("node_modules")
    return matches


def human_size(num_bytes):
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if num_bytes < 1024:
            return f"{num_bytes:.1f} {unit}"
        num_bytes /= 1024
    return f"{num_bytes:.1f} PB"


def dir_size(path):
    total = 0
    for dirpath, _dirnames, filenames in os.walk(path):
        for filename in filenames:
            filepath = os.path.join(dirpath, filename)
            if os.path.isfile(filepath):
                total += os.path.getsize(filepath)
    return total


def main():
    parser = argparse.ArgumentParser(
        description="Recursively find and delete all node_modules directories under a given directory."
    )
    parser.add_argument("directory", help="Root directory to search for node_modules")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="List node_modules directories that would be deleted without deleting them",
    )
    parser.add_argument(
        "-y", "--yes",
        action="store_true",
        help="Delete without prompting for confirmation",
    )
    args = parser.parse_args()

    root = os.path.abspath(args.directory)
    if not os.path.isdir(root):
        print(f"Error: '{root}' is not a valid directory", file=sys.stderr)
        sys.exit(1)

    print(f"Scanning '{root}' for node_modules directories...")
    matches = find_node_modules(root)

    if not matches:
        print("No node_modules directories found.")
        return

    print(f"\nFound {len(matches)} node_modules director{'y' if len(matches) == 1 else 'ies'}:")
    total_size = 0
    for path in matches:
        size = dir_size(path)
        total_size += size
        print(f"  {path} ({human_size(size)})")
    print(f"\nTotal size: {human_size(total_size)}")

    if args.dry_run:
        print("\nDry run: no directories were deleted.")
        return

    if not args.yes:
        answer = input("\nDelete all listed node_modules directories? [y/N] ").strip().lower()
        if answer != "y":
            print("Aborted.")
            return

    deleted = 0
    for path in matches:
        try:
            shutil.rmtree(path)
            deleted += 1
            print(f"Deleted: {path}")
        except OSError as exc:
            print(f"Failed to delete {path}: {exc}", file=sys.stderr)

    print(f"\nDeleted {deleted}/{len(matches)} node_modules directories.")


if __name__ == "__main__":
    main()
